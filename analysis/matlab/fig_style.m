function S = fig_style()
%FIG_STYLE Shared figure rules for the MATLAB redraws.
%   Sets LaTeX text everywhere, a three-size role ladder (axis labels 9 pt,
%   annotations 8 pt, tick labels 7 pt), outward ticks, no box, and returns
%   the first two MATLAB default line colours (blue, orange; colour-blind safe as a pair) plus size constants.

S.size.label = 9;     % axis labels and direct series labels
S.size.note  = 8;     % annotations, legend
S.size.tick  = 7;     % tick labels
S.size.letter = 10;   % panel letters (bold)

S.c.blue   = [0.0000 0.4470 0.7410];  % MATLAB default colour 1 (blue): within budget / supply resistance
S.c.orange = [0.8500 0.3250 0.0980];  % MATLAB default colour 2 (orange): over budget / manifold compliance
S.c.ink    = [0.15 0.15 0.15];      % axes and text
S.c.grey   = [0.55 0.55 0.55];      % reference lines
S.c.stem   = [0.80 0.80 0.80];      % lollipop stems, grid

set(groot, ...
    'defaultTextInterpreter', 'latex', ...
    'defaultAxesTickLabelInterpreter', 'latex', ...
    'defaultLegendInterpreter', 'latex', ...
    'defaultAxesFontSize', S.size.tick, ...
    'defaultAxesLabelFontSizeMultiplier', S.size.label / S.size.tick, ...
    'defaultAxesTitleFontSizeMultiplier', S.size.label / S.size.tick, ...
    'defaultTextFontSize', S.size.note, ...
    'defaultAxesTickDir', 'out', ...
    'defaultAxesTickLength', [0.012 0.012], ...
    'defaultAxesBox', 'off', ...
    'defaultAxesLineWidth', 0.6, ...
    'defaultAxesXColor', S.c.ink, ...
    'defaultAxesYColor', S.c.ink, ...
    'defaultAxesColor', 'none', ...
    'defaultFigureColor', 'w', ...
    'defaultLineLineWidth', 1.2);
end
