function make_access_tables(root, S)
%MAKE_ACCESS_TABLES Write the bounds and qualification tables as LaTeX tabular fragments.
%   Inputs: results/access-stability/bounds.csv and
%   evidence/access-stability-20261006/qualification.json. Outputs bounds_table.tex and
%   qualification_table.tex in results/access-stability (booktabs, siunitx, xcolor).
%   Every value is read from those files; nothing is typed here.

out = fullfile(root, 'results', 'access-stability');
opts = detectImportOptions(fullfile(out, 'bounds.csv'), 'Delimiter', ',');
opts = setvartype(opts, opts.VariableNames, 'string');
T = readtable(fullfile(out, 'bounds.csv'), opts);
thr = unique(T.threshold_min);
assert(isscalar(thr), 'bounds.csv: more than one threshold');

o = T(T.scenario == "original", :); w = T(T.scenario == "widened", :);
assert(isequal(o.node, w.node), 'bounds.csv: node order differs between scenarios');
rows = strings(height(o), 1);
for i = 1:height(o)
    rows(i) = sprintf('%s & %s & %s & %s & %s & %s & %s \\\\', o.node(i), ...
        cellnum(o.lower_min(i)), cellnum(o.upper_min(i)), decision(o.classification(i)), ...
        cellnum(w.lower_min(i)), cellnum(w.upper_min(i)), decision(w.classification(i)));
end
L = [
"% Generated by analysis/matlab/make_access_tables.m from bounds.csv; do not edit by hand."
colours(S)
"\begin{tabular}{@{}l S[table-format=2.0] S[table-format=2.0] l S[table-format=2.0] S[table-format=2.0] l@{}}"
"\toprule"
" & \multicolumn{3}{c}{Original assumptions} & \multicolumn{3}{c}{Widened assumptions} \\"
"\cmidrule(lr){2-4}\cmidrule(l){5-7}"
"Node & {$L$ (\unit{\minute})} & {$U$ (\unit{\minute})} & Decision & {$L$ (\unit{\minute})} & {$U$ (\unit{\minute})} & Decision \\"
"\midrule"
rows
"\bottomrule"
sprintf("\\multicolumn{7}{@{}l}{\\footnotesize Shortest time to Clinic: $L$ lower, $U$ upper. Threshold $\\tau = \\qty{%s}{\\minute}$: access if $U \\le \\tau$, exclusion if $L > \\tau$.}", thr)
"\end{tabular}"
];
writelines(L, fullfile(out, 'bounds_table.tex'));

Q = jsondecode(fileread(fullfile(root, 'evidence', 'access-stability-20261006', 'qualification.json')));
inputs = Q.development_baseline.inputs;
if isstruct(inputs), inputs = num2cell(inputs); end
rows = strings(numel(inputs), 1);
for i = 1:numel(inputs)
    r = inputs{i};
    name = char(r.input); name = [upper(name(1)) lower(name(2:end))];
    rows(i) = sprintf('%s & %s & %s \\\\', tex(name), tex(r.source), tex(r.qualification));
end
L = [
"% Generated by analysis/matlab/make_access_tables.m from qualification.json; do not edit by hand."
"\small"
"\begin{tabular}{@{}l >{\raggedright\arraybackslash}p{4.4cm} >{\raggedright\arraybackslash}p{8.6cm}@{}}"
"\toprule"
"Input & Recorded source & Qualification finding \\"
"\midrule"
join(rows, newline + "\addlinespace" + newline)
"\bottomrule"
"\end{tabular}"
];
writelines(L, fullfile(out, 'qualification_table.tex'));
end

function s = cellnum(v)
if v == "infinity", s = '{$\infty$}'; else, s = char(v); end
end

function s = decision(c)
switch c
    case "definite_access",    s = '\textcolor{access}{definite access}';
    case "definite_exclusion", s = '\textcolor{exclusion}{definite exclusion}';
    case "unresolved",         s = '\textcolor{ink}{unresolved}';
    otherwise, error('unknown decision %s', c);
end
end

function L = colours(S)
L = [sprintf("\\definecolor{access}{rgb}{%.4f,%.4f,%.4f}", S.c.blue)
     sprintf("\\definecolor{exclusion}{rgb}{%.4f,%.4f,%.4f}", S.c.orange)
     sprintf("\\definecolor{ink}{rgb}{%.2f,%.2f,%.2f}", S.c.ink)];
end

function s = tex(v)
%TEX Escape LaTeX special characters in a record string.
s = string(v);
s = replace(s, "\", "\textbackslash{}");
for ch = ["&", "%", "$", "#", "_", "{", "}"]
    s = replace(s, ch, "\" + ch);
end
s = replace(s, "~", "\textasciitilde{}");
s = replace(s, "^", "\textasciicircum{}");
s = char(s);
end
