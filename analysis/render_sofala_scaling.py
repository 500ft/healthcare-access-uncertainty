"""Render the compact scaling table from its sole numeric result source."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
record = json.loads((root/'evidence/sofala-scaling/scaling.json').read_text())
lines = ['# Current-network software scaling', '',
    'Synthetic times and closures on current Beira-area Sofala OSM topology.',
    'These are implementation checks. Historical Idai replication and healthcare accuracy remain unqualified.', '',
    '[Source and reproduction](../evidence/sofala-scaling/README.md) · [Numeric record](../evidence/sofala-scaling/scaling.json)', '',
    '| Nodes | Directed arcs | Median paired run (ms) | Range (ms) | Process peak RSS (MiB) | Endpoint error (min) |',
    '| ---: | ---: | ---: | ---: | ---: | ---: |']
for r in record['sizes']:
    lines.append(f"| {r['nodes']:,} | {r['arcs']:,} | {1000*r['median_seconds']:.3f} | {1000*r['min_seconds']:.3f} to {1000*r['max_seconds']:.3f} | {r['peak_process_rss_mib']:.1f} | {r['endpoint_max_abs_error_minutes']:.1f} |")
lines += ['', 'A paired run calls the production routine for both original and widened bounds.',
    'Ranges are observed timing extrema, not confidence intervals. RSS is the process',
    'high-water mark, including the full parsed fixture and preceding sizes, not incremental graph memory.',
    'The numeric record also gives components, unreachable origins, raw timings, oracle worlds and result hashes.', '',
    'Contains © OpenStreetMap contributors data, available under [ODbL 1.0](https://opendatacommons.org/licenses/odbl/1-0/).',
    'Generated by `python analysis/render_sofala_scaling.py` from the committed numeric record.', '']
(root/'results/sofala-scaling.md').write_text('\n'.join(lines))
